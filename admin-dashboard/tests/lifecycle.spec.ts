import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import {join} from 'node:path';

test('Siklus admin, aktivasi desktop, perpanjangan, perangkat, dan pencabutan',async({page,request})=>{
  const password=readFileSync(join(process.cwd(),'../work/e2e-runtime/password.txt'),'utf8');
  const stamp=Date.now();
  const desktopAPI=process.env.CHESSLAB_E2E_API||'http://127.0.0.1:8000';
  await page.goto('/');
  await page.getByLabel('Email administrator').fill('e2e@example.com');
  await page.getByLabel('Kata sandi',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Masuk ke dashboard'}).click();
  await expect(page.getByRole('heading',{name:'Ringkasan',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Pelanggan',exact:true}).click();
  await page.getByRole('button',{name:'Tambah pelanggan',exact:true}).click();
  let dialog=page.getByRole('dialog');
  await dialog.getByLabel('Nama pelanggan').fill('Pelanggan QA '+stamp);
  await dialog.getByLabel('Email pelanggan').fill(`qa-${stamp}@example.com`);
  await dialog.getByRole('button',{name:'Simpan',exact:true}).click();
  await expect(page.getByText('Pelanggan berhasil dibuat.')).toBeVisible();
  await page.getByRole('button',{name:'Lisensi',exact:true}).click();
  await page.getByRole('button',{name:'Buat lisensi'}).click();
  dialog=page.getByRole('dialog');
  await dialog.getByRole('combobox',{name:'Pelanggan',exact:true}).selectOption({label:`Pelanggan QA ${stamp} · qa-${stamp}@example.com`});
  await dialog.getByRole('combobox',{name:'Paket',exact:true}).selectOption({index:1});
  await dialog.getByRole('button',{name:'Simpan',exact:true}).click();
  await expect(dialog.getByRole('heading',{name:'Simpan kunci lisensi'})).toBeVisible();
  const key=(await dialog.locator('code.key').innerText()).trim();
  expect(key).toMatch(/^CLP-[0-9A-F]{40}$/);
  await dialog.getByRole('button',{name:'Tutup dialog'}).click();
  const device={product_code:'chesslab-pc',device_hash:'e'.repeat(64)};
  const activate=await request.post(desktopAPI+'/api/v1/licenses/activate',{data:{...device,license_key:key}});
  expect(activate.status()).toBe(200);
  const credential=(await activate.json()).activation_secret;
  await page.getByRole('button',{name:'Muat ulang',exact:true}).click();
  await page.getByRole('button',{name:key.slice(0,12)+'••••',exact:true}).click();
  dialog=page.getByRole('dialog');
  await expect(dialog.getByText('Perangkat terdaftar',{exact:true})).toHaveCount(0);
  await expect(dialog.locator('.badge.ACTIVE')).toBeVisible();
  await dialog.getByRole('button',{name:'Perpanjang',exact:true}).click();
  await page.getByLabel('Referensi pembayaran yang sudah dikonfirmasi').fill('QA-BANK-'+stamp);
  await page.getByRole('button',{name:'Konfirmasi tindakan',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Detail lisensi',exact:true})).toBeVisible();
  await expect(page.getByText('license.renewed',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Reset perangkat',exact:true}).click();
  await page.getByLabel('Alasan tindakan').fill('Pelanggan mengganti komputer untuk pengujian');
  await page.getByRole('button',{name:'Konfirmasi tindakan',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Detail lisensi',exact:true})).toBeVisible();
  const invalid=await request.post(desktopAPI+'/api/v1/licenses/validate',{data:device,headers:{Authorization:'Bearer '+credential}});
  expect(invalid.status()).toBe(403);
  await page.getByRole('button',{name:'Cabut',exact:true}).click();
  await page.getByLabel('Alasan tindakan').fill('Siklus QA selesai dan lisensi uji dicabut');
  await page.getByRole('button',{name:'Konfirmasi tindakan',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Detail lisensi',exact:true})).toBeVisible();
  await expect(page.getByRole('dialog').locator('.badge.REVOKED')).toBeVisible();
  await page.getByRole('button',{name:'Tutup dialog',exact:true}).click();
  await page.getByRole('button',{name:'Produk & paket',exact:true}).click();
  await page.getByRole('button',{name:'Tambah paket',exact:true}).click();
  await page.getByLabel('Nama paket',{exact:true}).fill('ChessLab 30 hari QA '+stamp);
  await page.getByLabel('Durasi (hari)',{exact:true}).fill('30');
  await page.getByLabel('Harga (rupiah)',{exact:true}).fill('250000');
  await page.getByRole('dialog').getByRole('button',{name:'Simpan',exact:true}).click();
  await expect(page.getByText('Konfigurasi paket disimpan.')).toBeVisible();
  await page.getByRole('button',{name:'Catatan audit',exact:true}).click();
  await page.getByLabel('Filter tindakan audit').fill('license.renewed');
  await expect(page.getByRole('cell',{name:'license.renewed',exact:true}).first()).toBeVisible();
  await page.getByRole('button',{name:'Ringkasan',exact:true}).click();
  await expect(page.getByText('Total lisensi',{exact:true})).toBeVisible();
  await expect(page.locator('.metric-value').first()).toHaveText(/^[1-9]\d*$/);
  await page.screenshot({path:'../work/dashboard-light.png',fullPage:true});
  await page.getByRole('button',{name:'Gunakan mode gelap'}).click();
  await page.screenshot({path:'../work/dashboard-dark.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('heading',{name:'Ringkasan',exact:true})).toBeVisible();
  await page.screenshot({path:'../work/dashboard-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Keluar',exact:true}).click();
  await expect(page.getByRole('button',{name:'Masuk ke dashboard'})).toBeVisible();
});
